const LANG_META = {
  en: { label: "English", dir: "ltr", locale: "en-GB" },
  nl: { label: "Nederlands", dir: "ltr", locale: "nl-NL" },
  ar: { label: "العربية", dir: "rtl", locale: "ar-EG" },
};

const LangCtx = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("garage_lang") || "en");
  useEffect(() => {
    localStorage.setItem("garage_lang", lang);
    const meta = LANG_META[lang];
    document.documentElement.setAttribute("dir", meta.dir);
    document.documentElement.setAttribute("lang", lang);
    document.body.classList.toggle("font-arabic", lang === "ar");
  }, [lang]);
  const t = (k, vars) => {
    let s = (DICT[lang] && DICT[lang][k]) || DICT.en[k] || k;
    if (vars) Object.entries(vars).forEach(([kk, v]) => { s = s.replace(`{${kk}}`, v); });
    return s;
  };
  return (
    <LangCtx.Provider value={{ lang, setLang, t, meta: LANG_META[lang], langs: LANG_META }}>
      {children}
    </LangCtx.Provider>
  );
}

export const useLang = () => useContext(LangCtx);
